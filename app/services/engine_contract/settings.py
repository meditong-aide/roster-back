@dataclass(frozen=True)
class HardLock:
    """CLAUDE.md 하드락 표 #1~#8 직접 구현 표지.

    `rule_no` 는 대표 규칙 번호(정렬·단일 분류용, 항상 1~8). `kind='boundary_switch'` 처럼
    규칙 하나가 아니라 **여러 규칙을 한꺼번에 켜고 끄는 스위치**(월경계 하드락 통째 해제 등)는
    `rule_nos`(비어 있지 않은 튜플)에 영향받는 규칙 번호 전부를 담는다 — EI-6 반박 검토 반영,
    기본값 `()` 은 '단일 규칙'(`rule_no` 그대로)을 뜻한다.
    """

    rule_no: int
    kind: str
    cap: object = None
    relax_when: str = ""
    rule_nos: tuple[int, ...] = ()


